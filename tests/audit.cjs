const assert=require('node:assert/strict');
const audit=require('../dist/audit.js');
const base={a:'A',b:'B',winner:'B',method:'Decision',p_a:.5};
assert.equal(audit.row(base).pick,null);
assert.equal(audit.row({...base,p_a:.51}).correct,false);
assert.equal(audit.row({...base,p_a:.49}).pick,'B');
assert.equal(audit.row({...base,p_a:null,p_limited:.7}).tier,'Limited history');
assert.equal(audit.row({...base,p_a:null,p_limited:null}).label,'No forecast');
assert.equal(audit.row({...base,winner:null,method:''}).status,'Pending');
assert.equal(audit.row({...base,winner:null,method:'No Contest'}).status,'Void');
const s=audit.summarize([base,{...base,p_a:.8},{...base,winner:null,method:''}]);
assert.equal(s.groups[0].coverage,.5);
assert.equal(s.groups[0].accuracy,0);
assert.equal(s.pending,1);
assert.ok(Math.abs(s.groups[0].brier-.445)<1e-10);
assert.equal(audit.outcome({...base,p_distance:.4},'p_distance').actual,1);
assert.equal(audit.outcome({...base,method:'Technical Decision',p_distance:.4},'p_distance'),null);
assert.equal(audit.outcome({...base,p_submission:NaN},'p_submission'),null);
const archive=require('../dist/results.json');
const real=audit.summarize(Object.values(archive['ufc-vegas-124'].bouts));
assert.deepEqual(real.groups.map(g=>[g.right,g.picks,g.tossups]),[[4,5,0],[6,8,1]]);
console.log('14 audit assertions passed; archived CL-1 4/5 and limited-history 6/8 preserved.');
